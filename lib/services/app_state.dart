  // Mulai subscribe stream sensor + relay dari Firebase
  void startIotSubscription() {
    final iot = IotService.instance;
    iot.startListening();

    iot.sensorStream.listen((data) {
      if (data.hasValidData) {
        soilMoisture = data.soilPersen.toDouble();
        airTemperature = data.suhu;
        airHumidity = data.humidity;
        waterTankLevel = data.waterLevelPersen.toDouble();
        hasValidSensorData = true;
        lastSensorTimestamp = data.lastUpdateDateTime;

        final dayIdx = (DateTime.now().weekday - 1).clamp(0, 6);
        weeklySoilMoisture[dayIdx] = soilMoisture;
        weeklyTemperature[dayIdx] = airTemperature;
        weeklyHumidity[dayIdx] = airHumidity;
        _throttledSaveSensorHistory();
      }
      isDeviceOnline = data.isOnline;
      isDeviceConnected = isDeviceOnline;
      connectionStatus = data.connectionStatus;
      notifyListeners();
    });

    iot.relayStream.listen((relay) {
      pumpStatus = relay.pompaAir;
      pesticideAStatus = relay.solenoidA;
      pesticideBStatus = relay.solenoidB;
      fertigationAutoMode = relay.autoMode;
      notifyListeners();
    });

    // Cek status online secara berkala, karena jika ESP mati, stream sensor berhenti memanggil onValue
    _onlineCheckTimer?.cancel();
    _onlineCheckTimer = Timer.periodic(const Duration(seconds: 3), (timer) {
      final bool currentOnline = iot.lastSensor.isOnline;
      final currentStatus = iot.lastSensor.connectionStatus;
      if (isDeviceOnline != currentOnline || connectionStatus != currentStatus) {
        isDeviceOnline = currentOnline;
        isDeviceConnected = currentOnline;
        connectionStatus = currentStatus;
        notifyListeners();
      }
    });
  }

