    void togglePump() {
    if (fertigationAutoMode) return; // Kunci jika mode otomatis nyala

    final newVal = !pumpStatus;
    pumpStatus = newVal;
    
    if (newVal) {
      _pumpStartTime = DateTime.now();
      pesticideAStatus = false;
      pesticideBStatus = false;
    } else {
      if (_pumpStartTime != null) {
        final sec = DateTime.now().difference(_pumpStartTime!).inSeconds;
        if (sec >= 1) {
          final liters = (sec * 0.1).clamp(0.1, 50.0);
          addWaterUsage(liters);
        }
        _pumpStartTime = null;
      }
    }

    notifyListeners();
    IotService.instance.setPompaAir(newVal);
  }

