  bool addSchedule(
    String time,
    String type,
    String volume,
    List<String> days, {
    String zone = 'Zona A',
    int durationSeconds = 20,
    String? recommendationId,
    String status = 'Aktif',
    String source = 'Manual',
  }) {
    // Cek duplikasi (FR-07, AC-8)
    final isDuplicate = schedules.any((s) {
      final sTime = s['time']?.toString() ?? '';
      final sZone = s['zone']?.toString() ?? 'Zona A';
      final sDays = (s['days'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [];
      return sTime == time && sZone == zone && sDays.any((d) => days.contains(d));
    });

    if (isDuplicate) return false;

    final newSchedule = {
      'id': 'sch_${DateTime.now().millisecondsSinceEpoch}',
      'time': time,
      'type': type,
      'volume': volume,
      'days': days,
      'zone': zone,
      'duration_seconds': durationSeconds,
      'status': status,
      'source': source,
      'recommendation_id': recommendationId,
      'createdAt': DateTime.now().toIso8601String(),
    };
    schedules.add(newSchedule);
    _saveSchedules();
    notifyListeners();
    return true;
  }

  void updateScheduleStatus(String id, String newStatus) {
    final idx = schedules.indexWhere((s) => s['id'] == id);
    if (idx != -1) {
      schedules[idx]['status'] = newStatus;
      _saveSchedules();
      notifyListeners();
    }
  }

  void removeSchedule(String id) {
    schedules.removeWhere((s) => s['id'] == id);
    _saveSchedules();
    notifyListeners();
  }

  void _saveSchedules() {
    final jsonStr = jsonEncode(schedules);
