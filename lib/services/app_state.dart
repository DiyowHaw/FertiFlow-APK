  void updateTreatmentStatus(String treatmentId, String newStatus) {
    final idx = treatments.indexWhere((t) => t['id'] == treatmentId);
    if (idx != -1) {
      final oldStatus = treatments[idx]['status'];
      treatments[idx] = Map<String, dynamic>.from(treatments[idx]);
      treatments[idx]['status'] = newStatus;

      // Update counter
      if (newStatus == 'done' && oldStatus != 'done') {
        if (needsAttentionCount > 0) needsAttentionCount--;
      } else if (newStatus != 'done' && oldStatus == 'done') {
        needsAttentionCount++;
      }

      notifyListeners();
    }
  }

  bool addTreatment(Map<String, dynamic> treatment) {
    final recId = treatment['recommendation_id']?.toString() ?? treatment['id']?.toString();
    // Cegah duplikasi rekomendasi di Panduan Penanganan (FR-06, AC-8)
    if (recId != null && treatments.any((t) => (t['recommendation_id'] ?? t['id'])?.toString() == recId)) {
      return false; // Sudah pernah ditambahkan
    }
    treatments.insert(0, treatment);
    needsAttentionCount++;
    _saveTreatments();
    notifyListeners();
    return true;
  }

  void deleteTreatment(String treatmentId) {
    final idx = treatments.indexWhere((t) => (t['id']?.toString() ?? '') == treatmentId);
    if (idx != -1) {
      final oldStatus = treatments[idx]['status'];
      treatments.removeAt(idx);
      if (oldStatus != 'done' && needsAttentionCount > 0) {
        needsAttentionCount--;
      }
      _saveTreatments();
      notifyListeners();
    }
  }

  void clearAllTreatments() {
    treatments.clear();
    needsAttentionCount = 0;
    _saveTreatments();
    notifyListeners();
  }

