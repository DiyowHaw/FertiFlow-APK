  void _checkAndExecuteSchedules() {
    final now = DateTime.now();
    final weekdayAliases = {
      1: ['sen', 'senin', 'mon', 'monday'],
      2: ['sel', 'selasa', 'tue', 'tuesday'],
      3: ['rab', 'rabu', 'wed', 'wednesday'],
      4: ['kam', 'kamis', 'thu', 'thursday'],
      5: ['jum', 'jumat', 'fri', 'friday'],
      6: ['sab', 'sabtu', 'sat', 'saturday'],
      7: ['min', 'minggu', 'sun', 'sunday'],
    };
    final validTodayAliases = weekdayAliases[now.weekday] ?? ['sen'];
    final dateKey = "${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}";

    for (var i = 0; i < schedules.length; i++) {
      final s = schedules[i];
      final days = (s['days'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [];
      final time = s['time']?.toString() ?? '';
      final status = s['status']?.toString() ?? 'Aktif';

      if (status == 'Nonaktif' || status == 'Sedang Berjalan') continue;

      // 1. Cek Hari: Cocokkan hari ini dengan daftar hari jadwal
      final isMatchDay = days.any((d) => validTodayAliases.contains(d.trim().toLowerCase()));

      // 2. Cek Jam & Menit: Bersihkan format (e.g. "06:00", "6:00", "06:00 WIB")
      final cleanTime = time.replaceAll(RegExp(r'[^0-9:]'), '').trim();
      final timeParts = cleanTime.split(':');
      bool isMatchTime = false;
      if (timeParts.length >= 2) {
        final h = int.tryParse(timeParts[0]) ?? -1;
        final m = int.tryParse(timeParts[1]) ?? -1;
        isMatchTime = (h == now.hour && m == now.minute);
      }

      if (isMatchDay && isMatchTime) {
        final execKey = "${s['id']}_${dateKey}_${now.hour}_${now.minute}";
        if (s['lastExecutedKey'] == execKey) {
          continue; // Sudah dieksekusi hari ini pada menit ini
        }

        final String targetZone = s['zone']?.toString() ?? 'Zona A';
        final String type = s['type']?.toString() ?? 'Air';
        final bool isWater = (type.toLowerCase() == 'air');

        // Mencegah konflik jika pompa sedang aktif
        if (isWater && pumpStatus) continue;
        if (!isWater && (pesticideAStatus || pesticideBStatus)) continue;

        // ─── EKSEKUSI PENYIRAMAN / PEMUPUKAN ───
        s['lastExecutedKey'] = execKey;
        s['status'] = 'Sedang Berjalan';
        final int rawDuration = (s['duration_seconds'] as num?)?.toInt() ?? 20;
        final int safeDuration = rawDuration.clamp(5, 60); // Batas aman max 60 detik

        debugPrint('[Scheduler] EKSEKUSI: $type ($targetZone, $safeDuration s) jam ${now.hour}:${now.minute}');

        if (isWater) {
          pumpStatus = true;
          IotService.instance.setPompaAir(true);
        } else {
          if (targetZone == 'Zona B') {
            pesticideBStatus = true;
            IotService.instance.setPestisidaB(true);
          } else {
            pesticideAStatus = true;
            IotService.instance.setPestisidaA(true);
          }
        }

        addActivityLogItem(
          type: 'schedule_run',
          title: isWater ? 'Penyiraman Otomatis Dimulai' : 'Pemupukan Otomatis Dimulai',
          description: 'Menjalankan $type untuk $targetZone selama $safeDuration detik sesuai jadwal ($cleanTime WIB).',
          status: 'Sedang Berjalan',
          zone: targetZone,
        );
        _saveSchedules();
        notifyListeners();

        // Mati otomatis setelah durasi selesai (FR-13)
        Timer(Duration(seconds: safeDuration), () {
          if (isWater) {
            IotService.instance.setPompaAir(false);
