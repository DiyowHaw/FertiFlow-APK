  Future<void> loadFromDatabase() async {
    final db = DatabaseService.instance;

    final savedTheme = await db.getSetting('themeMode');
    if (savedTheme == 'dark') {
      themeMode = ThemeMode.dark;
    } else {
      themeMode = ThemeMode.light;
    }

    final savedLocale = await db.getSetting('locale');
    if (savedLocale == 'en') {
      _locale = const Locale('en');
    } else {
      _locale = const Locale('id');
    }

    final loginVal = await db.getSetting('isLoggedIn');
    isLoggedIn = loginVal == 'true';

    final savedName = await db.getSetting('userName');
    if (savedName != null) userName = savedName;

    final savedEmail = await db.getSetting('userEmail');
    if (savedEmail != null) userEmail = savedEmail;

    final savedPhoto = await db.getSetting('userPhoto');
    if (savedPhoto != null) userPhoto = savedPhoto;

    final savedSchedules = await db.getSetting('schedules');
    if (savedSchedules != null) {
      try {
        final decoded = jsonDecode(savedSchedules) as List<dynamic>;
        schedules = decoded.map((e) => Map<String, dynamic>.from(e)).toList();
      } catch (_) {}
    }

    final savedTreatments = await db.getSetting('treatments');
    if (savedTreatments != null) {
      try {
        final decoded = jsonDecode(savedTreatments) as List<dynamic>;
        treatments = decoded
            .map((e) => Map<String, dynamic>.from(e))
            .where((t) {
              final id = t['id']?.toString() ?? '';
              // Bersihkan mock data bawaan lama (t_1, t_2, t_3, mock, dummy)
              return !id.startsWith('t_') && !id.contains('mock') && !id.contains('dummy');
            })
            .toList();
        needsAttentionCount = treatments.where((t) => t['status'] != 'done').length;
        _saveTreatments(); // Simpan versi bersih kembali ke DB agar data lama terhapus permanen
      } catch (_) {}
    } else {
      treatments = [];
      needsAttentionCount = 0;
    }

    final savedWater = await db.getSetting('weekly_water_usage');
    if (savedWater != null) {
      try {
        final decoded = jsonDecode(savedWater) as List<dynamic>;
        weeklyWaterUsage = decoded.map((e) => (e as num).toDouble()).toList();
      } catch (_) {}
    }

    final savedSoil = await db.getSetting('weekly_soil_moisture');
    if (savedSoil != null) {
      try {
        final decoded = jsonDecode(savedSoil) as List<dynamic>;
        weeklySoilMoisture = decoded.map((e) => (e as num).toDouble()).toList();
